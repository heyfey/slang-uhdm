# r10v104 w5 generator -- widths x declared types x homes x read faces.
# MEASUREMENT ONLY.  One localparam per module, one read face per module.
W = [1, 4, 32]
TYPES = {
    "lg": lambda w: f"logic [{w-1}:0]",
    "bt": lambda w: f"bit [{w-1}:0]",
    "td": lambda w: f"tw5_{w}_t",
}
# read faces: none / bare / select
FACES = ["n", "b", "s"]

L = []
L.append("// r10v104 w5 -- widths {1,4,32} x types {logic,bit,typedef} x homes")
L.append("// {top module, submodule, interface, gen scope} x reads {none,bare,select}.")
L.append("// MEASUREMENT ONLY.  Generated by gen_w5.py.")
for w in W:
    L.append(f"typedef logic [{w-1}:0] tw5_{w}_t;")
L.append("module subw5 #(parameter int P = 0) (output logic z); assign z = |P; endmodule")

def body(decl, face, w):
    out = [f"  localparam {decl} X = {{{w}{{1'b1}}}};"]
    if face == "b":
        out.append("  logic [X:0] wb; assign wb = '0;")
    elif face == "s":
        out.append("  logic [X[0]:0] ws; assign ws = '0;")
    return out

insts = []
ifinsts = []
for w in W:
    for tn, tf in TYPES.items():
        for f in FACES:
            nm = f"m_{tn}{w}{f}"
            # home = submodule
            L.append(f"module {nm} (output logic o);")
            L += body(tf(w), f, w)
            L.append("  assign o = 1'b0;")
            L.append("endmodule")
            insts.append(nm)
            # home = interface
            inm = f"if_{tn}{w}{f}"
            L.append(f"interface {inm} ();")
            L += body(tf(w), f, w)
            L.append("  logic d; assign d = 1'b0;")
            L.append("endinterface")
            ifinsts.append(inm)
            # home = generate scope inside a submodule
            gnm = f"g_{tn}{w}{f}"
            L.append(f"module {gnm} (output logic o);")
            L.append("  for (genvar gg = 0; gg < 1; gg++) begin : gs")
            L += ["  " + x for x in body(tf(w), f, w)]
            L.append("  end")
            L.append("  assign o = 1'b0;")
            L.append("endmodule")
            insts.append(gnm)

L.append("module w5_cross104 (input logic ext, output logic o);")
# home = TOP module itself (the arm's own top)
for w in W:
    for tn, tf in TYPES.items():
        for f in FACES:
            d = tf(w)
            L.append(f"  localparam {d} T_{tn}{w}{f} = {{{w}{{1'b1}}}};")
            if f == "b":
                L.append(f"  logic [T_{tn}{w}{f}:0] tb_{tn}{w}{f}; assign tb_{tn}{w}{f} = '0;")
            elif f == "s":
                L.append(f"  logic [T_{tn}{w}{f}[0]:0] ts_{tn}{w}{f}; assign ts_{tn}{w}{f} = '0;")
for i, nm in enumerate(insts):
    L.append(f"  {nm} u_{nm} (.o());")
for i, nm in enumerate(ifinsts):
    L.append(f"  {nm} u_{nm} ();")
L.append("  assign o = ext;")
L.append("endmodule")
open("/tmp/v104_arms/w5_cross104.sv", "w").write("\n".join(L) + "\n")
print("cells:", len(insts) + len(ifinsts) + len(W)*len(TYPES)*len(FACES))
