#!/usr/bin/env python3
"""r10earl80 — generate g1_hops80.sv: the OVERRIDE-CHAIN DECOMPILE-WIDTH grid.

MEASUREMENT ONLY.  The official uhdm-cmp remains the sole judge.

Every family is the Earlgrey shape, exactly:
    top  --.A(<S>)-->  h1(<M> A)  --.B(A)-->  h2(int unsigned B)
                                   --.D(B)-->  lf(int unsigned D)
so the param_assign of A is the ZERO-hop cell, B the ONE-hop cell and D the
TWO-hop cell, and the axes are the WRITTEN literal <S> and the intermediate
formal's DECLARED type <M>.

Three homes for the source value:
  DECL  the literal is A's own declared DEFAULT and top does not override
  OVR   the literal is WRITTEN AT THE INSTANTIATION SITE  (Earlgrey's shape)
  LP    the literal initialises a top-level localparam of type <M> and the
        instantiation passes THAT      (r10earl27/28's qc28 shape)
"""
import sys

GRIDS = {
 # g1 — the WIDTH axis: does the decompile keep the SOURCE width down the chain?
 "g1": (["4'h2", "8'h2", "4'd2", "4'b10", "4'o2", "'0", "'h2", "2",
         "16'h2", "1'b1", "4'h0", "33'h1"],
        [("bit [3:0]", "b4"), ("bit [7:0]", "b8"), ("logic [7:0]", "l8"),
         ("int unsigned", "iu"), ("int", "ii"), ("bit [31:0]", "b32"),
         ("", "un"), ("bit", "b1")]),
 # g2 — the TRUNCATION/SIGN axis: does an intermediate hop MASK, TRUNCATE or
 # SIGN-EXTEND the value it carries (adjustSize's UINT / logic-BIN / int-BIN
 # arms), or does the raw override Value pass through untouched?
 "g2": (["8'b10110011", "8'hff", "300", "4'sb1000", "8'sh80", "16'habcd",
         "2", "1'sb1", "8'd200", "5'b11111"],
        [("bit [3:0]", "b4"), ("logic [3:0]", "l4"), ("int", "ii"),
         ("int unsigned", "iu"), ("bit [7:0]", "b8"), ("logic [7:0]", "l8"),
         ("bit", "b1"), ("logic signed [3:0]", "ls4")]),
}
import os
_G = os.environ.get("GRID80", "g1")
SRC, MID = GRIDS[_G]

def main():
    out = ["// r10earl80 g1_hops80.sv — GENERATED by gengrid80.py.  Do not edit.",
           "// MEASUREMENT ONLY."]
    tops = []
    lps = []
    k = 0
    for si, s in enumerate(SRC):
        for m, mtag in MID:
            for home in ("DECL", "OVR", "LP"):
                k += 1
                n = "p80_%s_%s_%d" % (mtag, home.lower(), si)
                decl = ("parameter %s A = %s" % (m, s)) if m else \
                       ("parameter A = %s" % s)
                out.append("module %s_lf #(parameter int unsigned D = 4)();" % n)
                out.append("  wire [31:0] w = D; endmodule")
                out.append("module %s_h2 #(parameter int unsigned B = 2)();" % n)
                out.append("  %s_lf #(.D(B)) u(); endmodule" % n)
                out.append("module %s_h1 #(%s)();" % (n, decl))
                out.append("  %s_h2 #(.B(A)) u(); endmodule" % n)
                if home == "DECL":
                    tops.append("  %s_h1 u_%d();" % (n, k))
                elif home == "OVR":
                    tops.append("  %s_h1 #(.A(%s)) u_%d();" % (n, s, k))
                else:
                    lp = "lp_%d" % k
                    lps.append("  localparam %s %s = %s;" %
                               (m if m else "", lp, s))
                    tops.append("  %s_h1 #(.A(%s)) u_%d();" % (n, lp, k))
    out.append("module top80();")
    out.extend(lps)
    out.extend(tops)
    out.append("endmodule")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")
    print("families=%d" % k)

main()
