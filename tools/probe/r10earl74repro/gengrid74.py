#!/usr/bin/env python3
"""r10earl74 — generate g1_dims74.sv: the DIMENSION-BOUND ENCODING grid.

Axes
  * the dimension SPELLING: size form [D], ranged [D-1:0], [0:D-1],
    two dims [D][2], a PACKED bound [D-1:0], an array_net, a typedef'd
    unpacked array;
  * what the dimension READS: an OVERRIDDEN instance parameter (actual =
    * / / / + / - / << / $clog2 / bare ref / literal / a localparam whose
    own init is one of those), a MODULE localparam with each init operator,
    a PACKAGE parameter (qualified and wildcard-imported), a genvar-derived
    localparam;
  * the HOME: module body, gen-for, nested gen, 1..3 instances.

MEASUREMENT ONLY.  usage: gengrid74.py > g1_dims74.sv
"""
import sys

# (tag, initializer text) for a module localparam / package localparam
INITS = [
    ("lit",  "8"),
    ("mul",  "A * B"),
    ("div",  "A / B"),
    ("sub",  "A - B"),
    ("add",  "A + B"),
    ("mod",  "A % 7"),
    ("pow",  "2 ** B"),
    ("shl",  "B << 2"),
    ("shr",  "A >> 5"),
    ("band", "A & 384"),
    ("clog", "$clog2(A)"),
    ("ref",  "A"),
    ("tern", "(A > B) ? 8 : 4"),
    ("cast", "int'(A / B)"),
]
# actuals for an overridden instance parameter
ACTS = [
    ("mul",  "A * B"),
    ("div",  "A / B"),
    ("sub",  "A - B"),
    ("add",  "A + B"),
    ("shl",  "B << 2"),
    ("clog", "$clog2(A)"),
    ("ref",  "A"),
    ("lit",  "8"),
    ("lmul", "LM"),     # bare ref to a MULT localparam  <- the Earlgrey shape
    ("ladd", "LA"),     # bare ref to an ADD  localparam
    ("lclog","LC"),     # bare ref to a $clog2 localparam
    ("plit", "pk74::PP"),
    ("pmul", "pk74::PM"),
]

o = sys.stdout.write

o("// GENERATED by gengrid74.py -- r10earl74 dimension-bound encoding grid.\n")
o("package pk74;\n")
o("  parameter  int PP  = 8;\n")
o("  localparam int PM  = 4 * 2;\n")
o("  localparam int PA  = 4 + 4;\n")
o("  localparam int PC  = $clog2(256);\n")
o("  localparam     PU  = 4 * 2;\n")
o("endpackage\n\n")

# ---- the sink: every dimension spelling, sized by ONE parameter D --------
o("module snk74 #(\n  parameter int D = 4\n) (\n"
  "  input logic [3:0] pin_i [D]\n);\n")
o("  logic [3:0]   s_sz  [D];\n")
o("  logic [3:0]   s_rg  [D-1:0];\n")
o("  logic [3:0]   s_z   [0:D-1];\n")
o("  logic [3:0]   s_2d  [D][2];\n")
o("  logic [D-1:0] s_pk;\n")
o("  wire  [3:0]   s_net [D];\n")
o("  typedef logic [3:0] s_td_t [D];\n")
o("  s_td_t        s_td;\n")
o("endmodule\n\n")

# ---- home 1: a module body, one localparam per initializer shape ---------
def dims(pfx, expr):
    o("  logic [3:0]   %s_sz  [%s];\n"   % (pfx, expr))
    o("  logic [3:0]   %s_rg  [%s-1:0];\n" % (pfx, expr))
    o("  logic [3:0]   %s_z   [0:%s-1];\n" % (pfx, expr))
    o("  logic [%s-1:0] %s_pk;\n"        % (expr, pfx))
    o("  wire  [3:0]   %s_net [%s];\n"   % (pfx, expr))

o("module home74 ();\n")
o("  import pk74::*;\n")
o("  localparam int A = 256;\n  localparam int B = 2;\n")
for tag, init in INITS:
    o("  localparam int L%s = %s;\n" % (tag, init))
o("  localparam     Lumul = A * B;\n")   # UNTYPED, mult
o("  localparam     Lulit = 8;\n")       # UNTYPED, literal
for tag, _ in INITS:
    dims("h_" + tag, "L" + tag)
dims("h_umul", "Lumul")
dims("h_ulit", "Lulit")
dims("h_qpm",  "pk74::PM")     # QUALIFIED package localparam, mult init
dims("h_qpp",  "pk74::PP")     # QUALIFIED package parameter, literal
dims("h_qpc",  "pk74::PC")     # QUALIFIED package localparam, $clog2
dims("h_wpm",  "PM")           # WILDCARD-imported, mult init
dims("h_wpp",  "PP")
dims("h_wpu",  "PU")           # wildcard, UNTYPED mult
o("endmodule\n\n")

# ---- home 2: a gen-for body, and a genvar-derived localparam -------------
o("module geng74 ();\n")
o("  localparam int A = 256;\n  localparam int B = 2;\n")
o("  for (genvar gi = 0; gi < 2; gi++) begin : gblk\n")
o("    localparam int Gmul = A * B;\n")
o("    localparam int Gadd = A + B;\n")
o("    localparam int Gclog = $clog2(A);\n")
o("    localparam int Ggv  = (gi + 1) * 4;\n")   # genvar-derived
o("    localparam int Ggvs = gi + 8;\n")
for t in ("Gmul", "Gadd", "Gclog", "Ggv", "Ggvs"):
    o("    logic [3:0]   g_%s_sz [%s];\n" % (t, t))
    o("    logic [3:0]   g_%s_rg [%s-1:0];\n" % (t, t))
    o("    logic [%s-1:0] g_%s_pk;\n" % (t, t))
o("    for (genvar gj = 0; gj < 2; gj++) begin : nblk\n")
o("      localparam int Nmul = A * B;\n")
o("      localparam int Nadd = A + B;\n")
o("      logic [3:0] n_mul_sz [Nmul];\n")
o("      logic [3:0] n_add_sz [Nadd];\n")
o("    end\n")
o("  end\n")
o("endmodule\n\n")

# ---- home 3: the OVERRIDE grid — one sink instance per actual ------------
o("module ovr74 ();\n")
o("  localparam int A = 256;\n  localparam int B = 2;\n")
o("  localparam int LM = A * B;\n")
o("  localparam int LA = A + B;\n")
o("  localparam int LC = $clog2(A);\n")
for tag, act in ACTS:
    o("  logic [3:0] w_%s [%s];\n" % (tag, act if tag not in ("lit",) else "8"))
    o("  snk74 #(.D(%s)) u_%s (.pin_i(w_%s));\n" % (act, tag, tag))
o("endmodule\n\n")

# ---- home 4: a TWO-HOP override chain (the Earlgrey shape) ---------------
o("module mid74 #(\n  parameter int MD = 4\n) (\n  input logic [3:0] pin_i [MD]\n);\n")
o("  logic [3:0] m_sz [MD];\n")
o("  snk74 #(.D(MD)) u_leaf (.pin_i(pin_i));\n")
o("endmodule\n\n")
o("module chain74 ();\n")
o("  localparam int A = 256;\n  localparam int B = 2;\n")
o("  localparam int CM = A * B;\n")
o("  localparam int CA = A + B;\n")
o("  logic [3:0] c_m [CM];\n  logic [3:0] c_a [CA];\n  logic [3:0] c_l [8];\n")
o("  mid74 #(.MD(CM)) u_cm (.pin_i(c_m));\n")
o("  mid74 #(.MD(CA)) u_ca (.pin_i(c_a));\n")
o("  mid74 #(.MD(8))  u_cl (.pin_i(c_l));\n")
o("endmodule\n\n")

o("module top74 ();\n  home74 u_home ();\n  geng74 u_geng ();\n"
  "  ovr74 u_ovr ();\n  chain74 u_chain ();\nendmodule\n")
