#!/usr/bin/env python3
"""r10earl88 - generate g1_elemdims88.sv: the ELEMENT-KIND x DIMENSION x
DIRECTION grid for a port/signal whose type is written `pkg::T`.

Element kinds are chosen to separate the TWO struct member scans Surelog runs:
  LOOSE  (NetlistElaboration elab_signal_, struct_typespec arm) - logic OR struct
  STRICT (SURELOG::Struct::isNet())                             - logic ONLY
`s_nest` is the only kind where they disagree, and it is the head's shape.
The leaf is instantiated THREE times (driven / undriven / inside a generate-for)
because earl77's R3 showed the struct arm can depend on drivenness.
"""
KINDS = [
    ("s_flat", "struct packed { logic a; logic [3:0] b; }"),                        # LOOSE 1 STRICT 1
    ("s_nest", "struct packed { struct packed { logic q; } en; logic [3:0] b; }"),  # LOOSE 1 STRICT 0
    ("s_enum", "struct packed { logic a; e88_t e; }"),                              # LOOSE 0 STRICT 0
    ("s_bit",  "struct packed { logic a; bit b; }"),                                # LOOSE 0 STRICT 0
    ("s_parr", "struct packed { logic a; logic [1:0][2:0] c; }"),                   # LOOSE 0 STRICT 0
    ("s_deep", "struct packed { struct packed { struct packed { logic q; } i; } o; }"),
]
SIMPLE = [("e88", None), ("v8", None), ("s1", None), ("b8", None)]
DIMS = [("d0", ""), ("d1", "[1:0]"), ("d2", "[1:0][2:0]")]
DIRS = [("i", "input"), ("o", "output")]

L = []
L.append("// r10earl88 g1 - GENERATED by gen88.py.  MEASUREMENT ONLY.")
L.append("package p88;")
L.append("  typedef enum logic [1:0] { E88A, E88B } e88_t;")
for n, d in KINDS:
    L.append("  typedef %s %s_t;" % (d, n))
L.append("  typedef logic [7:0] v8_t;")
L.append("  typedef logic       s1_t;")
L.append("  typedef bit   [7:0] b8_t;")
L.append("endpackage")
L.append("")
ports, conns, decls = [], [], []
allk = [(n, None) for n, _ in KINDS] + [("e88", None), ("v8", None), ("s1", None), ("b8", None)]
for kn, _ in allk:
    for dn, dt in DIMS:
        for pn, pd in DIRS:
            nm = "%s_%s_%s" % (pn, kn, dn)
            ports.append("  %-6s p88::%s_t %-9s %s" % (pd, kn, dt, nm))
            decls.append("  p88::%s_t %-9s w_%s;" % (kn, dt, nm))
            conns.append(".%s(w_%s)" % (nm, nm))
L.append("module leaf88 (")
L.append(",\n".join(ports))
L.append(");")
L.append("endmodule")
L.append("")
L.append("module top88;")
L += decls
CH = 6
cs = [", ".join(conns[i:i + CH]) for i in range(0, len(conns), CH)]
L.append("  leaf88 u_drv (")
L.append(",\n".join("    " + c for c in cs))
L.append("  );")
L.append("  leaf88 u_und ();")          # every port UNCONNECTED (earl77 R3)
for c in conns:
    nm = c[1:c.index("(")]
    if nm.startswith("i_"):
        L.append("  assign w_%s = w_o%s;" % (nm, nm[1:]))
L.append("  for (genvar gi88 = 0; gi88 < 2; gi88++) begin : g88")
L.append("    leaf88 u_gen (")
L.append(",\n".join("      " + c for c in cs))
L.append("    );")
L.append("  end")
L.append("endmodule")
open("g1_elemdims88.sv", "w").write("\n".join(L) + "\n")
print("wrote g1_elemdims88.sv: %d ports x 3 instances" % len(ports))
