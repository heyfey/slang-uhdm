#!/bin/bash
# r10ladder1/genvpinames.sh — build the int->vpi-name table ctladder consumes.
#
# UHDM ships NO int->name table for vpi properties/relations (there is
# `UhdmName(UHDM_OBJECT_TYPE)` for object kinds and nothing for the property
# ints), so ctladder's generic field sweep would otherwise print bare integers
# and the family keys would be unreadable.  This script scrapes the THREE
# installed vpi headers and emits one row per (int, name).  MANY ints carry
# more than one name (the property and the relation number spaces overlap), so
# the table is a MULTI-map and ctladder joins every name for an int with '|' —
# printing one arbitrary winner would silently mislabel fields.
#
# usage: genvpinames.sh [<include-dir>] > vpinames.inc
set -u
INC=${1:-$HOME/.local/include/uhdm}
for f in vpi_user.h sv_vpi_user.h uhdm_vpi_user.h; do
  [ -f "$INC/$f" ] || { echo "FATAL: no $INC/$f" >&2; exit 3; }
done
echo "// GENERATED by genvpinames.sh from $INC -- do not hand-edit."
cat "$INC"/vpi_user.h "$INC"/sv_vpi_user.h "$INC"/uhdm_vpi_user.h |
  sed -n 's/^#define[[:space:]]\+\(vpi[A-Za-z0-9_]*\)[[:space:]]\+\([0-9]\+\).*/{\2, "\1"},/p' |
  sed 's/^{//' | sort -u | sort -n -s | sed 's/^/{/'
