#!/usr/bin/env python3
"""r10earl73 — generate the golden grid for the param_assign VALUE-ENCODING law.

MEASUREMENT ONLY.  Crosses the DECLARED TYPE of a child module's parameter
against the SHAPE of the instantiation ACTUAL, in three homes (module scope,
gen-for, nested gen), and records the NON-OVERRIDDEN default too.

usage: gengrid73.py > g1_shapes73.sv
"""
TYPES = [
    ('int',  'parameter int P = 256'),
    ('unt',  'parameter P = 256'),
    ('bitr', 'parameter bit [9:0] P = 256'),
    ('logr', 'parameter logic [31:0] P = 256'),
    ('itg',  'parameter integer P = 256'),
    ('sgn',  'parameter signed [15:0] P = 256'),
]
# name -> actual text.  A = 256, B = 2 (both `parameter int` of the parent).
ACT = [
    ('none',  None),            # NOT overridden: measures the default's tag
    ('lit',   '128'),
    ('blit',  "8'd128"),
    ('hlit',  "'h80"),
    ('refa',  'A'),
    ('div',   'A / B'),
    ('mul',   'A * B'),
    ('sub',   'A - B'),
    ('add',   'A + B'),
    ('shl',   'B << 1'),
    ('shr',   'A >> 1'),
    ('clog',  '$clog2(A)'),
    ('tern',  '(A > B) ? 1 : 2'),
    ('cast',  "int'(A)"),
    ('conc',  '{B, B}'),
    ('neg',   '-B'),
    ('mod',   'A % B'),
    ('band',  'A & B'),
    ('bxor',  'A ^ B'),
    ('eq',    'A == B'),
    ('pow',   '2 ** B'),
    ('tpow',  '(A > B) ? 2 ** B : 4'),
    ('divl',  '256 / 2'),
    ('mulm',  'A * B / B'),
]

out = []
w = out.append
w('// r10earl73 grid g1 — declared type x override-actual shape.')
w('// MEASUREMENT ONLY.  Generated by gengrid73.py.')
w('')
for tn, decl in TYPES:
    w('module ch73_%s #(%s) ();' % (tn, decl))
    w('  localparam int USE_%s = 1;' % tn)
    w('endmodule')
    w('')
# A child whose OWN default is an expression over its own parameters
# (the AlignedMuxSize / non-overridden shape).
w('module ch73_dflt #(parameter int A0 = 256, parameter int B0 = 2) ();')
for nm, a in ACT:
    if a is None or 'A' not in a and 'B' not in a:
        continue
    w('  localparam int D_%s = %s;' % (nm, a.replace('A', 'A0').replace('B', 'B0')))
w('endmodule')
w('')
w('module top73;')
w('  parameter int A = 256;')
w('  parameter int B = 2;')
for tn, _ in TYPES:
    for nm, a in ACT:
        if a is None:
            w('  ch73_%s u_%s_%s ();' % (tn, tn, nm))
        else:
            w('  ch73_%s #(.P(%s)) u_%s_%s ();' % (tn, a, tn, nm))
w('  ch73_dflt u_dflt ();')
w('endmodule')
w('')
# GEN-FOR home: the same cells inside a generate-for, two iterations.
w('module top73g;')
w('  parameter int A = 256;')
w('  parameter int B = 2;')
w('  for (genvar g = 0; g < 2; g++) begin : gb')
for nm, a in ACT:
    if a is None:
        w('    ch73_int u_int_%s ();' % nm)
    else:
        w('    ch73_int #(.P(%s)) u_int_%s ();' % (a, nm))
w('  end')
w('endmodule')
w('')
# NESTED gen home + three instances of the containing module.
w('module top73n;')
w('  parameter int A = 256;')
w('  parameter int B = 2;')
w('  for (genvar g = 0; g < 2; g++) begin : ob')
w('    for (genvar h = 0; h < 2; h++) begin : ib')
for nm, a in ACT:
    if a is None:
        w('      ch73_int u_int_%s ();' % nm)
    else:
        w('      ch73_int #(.P(%s)) u_int_%s ();' % (a, nm))
w('    end')
w('  end')
w('endmodule')
w('')
w('module top73m;')
w('  top73n n0 ();')
w('  top73n n1 ();')
w('  top73n n2 ();')
w('endmodule')
print('\n'.join(out))
