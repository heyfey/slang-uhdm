#!/usr/bin/env python3
"""r10earl82 — generator for `g5_enc82.sv`, THE DISCRIMINATOR GRID.

MEASUREMENT ONLY.  Every cell is the SAME family — a RANGE BOUND that is a
bare read of a parameter — and only two things vary: WHAT the bound names
(home x declared type x initialiser x whether the instantiation overrides it,
and with what) and WHICH range consumer holds it (a packed net range, the
packed range of a struct-typedef array variable — the head's own shape — and
an unpacked range-form dimension).

The grid exists to answer one question with golden, not with argument: for
which (referent, consumer) cells is golden's bound the parameter's DECLARED
width, for which is it the unsized 64, and is there a third rule.
"""
import sys

# name, declared type, default, override actual (None = never overridden)
PARAMS = [
    ('NOI', 'int',            '8',    None),
    ('NOU', '',               '8',    None),
    ('NOB', 'byte',           '8',    None),
    ('NOS', 'shortint',       '8',    None),
    ('NOL', 'longint',        '8',    None),
    ('NOG', 'integer',        '8',    None),
    ('NOV', 'bit [3:0]',      "4'h7", None),
    ('NOW', 'logic [7:0]',    '8',    None),
    ('NOZ', 'int unsigned',   '8',    None),
    ('NOD', 'int',            "8'd8", None),
    ('NOX', 'int',            '4+4',  None),
    ('OVI', 'int',            '1',    '8'),
    ('OVU', '',               '1',    '8'),
    ('OVB', 'byte',           '1',    '8'),
    ('OVV', 'bit [3:0]',      "4'h1", "4'h7"),
    ('OVH', 'int',            '1',    "8'd8"),
    ('OVX', 'int',            '1',    '4+4'),
    ('OVN', 'int',            '1',    'SRC'),
    ('OVW', 'int',            '1',    '(8)'),
    # THE OVERRIDE-ACTUAL-IS-A-NAME axis, and it is the whole third rule:
    # what a bare-reference actual LENDS is the referenced parameter's own
    # stored width, so the referenced parameter's own shape is what varies.
    ('OVE', 'int',            '1',    'EXPR_LP'),   # -> module localparam int, EXPRESSION init
    ('OVQ', 'int',            '1',    'pk5_82::PKX'),  # -> package int, EXPRESSION init
    ('OVP', 'int',            '1',    'pk5_82::PKI'),  # -> package int, LITERAL init
    ('OVJ', 'byte',           '1',    'SRC'),       # byte formal <- int actual: WHOSE width?
    ('OVK', 'int',            '1',    'pk5_82::PKB'),  # int formal <- byte actual
    ('OVA', 'int',            '1',    'ARITH_LP'),  # -> module localparam int, `X-1` init
]
LOCALS = [
    ('LPI', 'int',         '8'),
    ('LPU', '',            '8'),
    ('LPB', 'byte',        '8'),
    ('LPV', 'bit [3:0]',   "4'h7"),
    ('LPX', 'int',         '4+4'),
]
PKGS = [
    ('PKI', 'int',         '8'),
    ('PKM', 'int',         'PKI - 1'),   # an ARITHMETIC-init package param (paramIntEnc)
    ('PKU', '',            '8'),
    ('PKB', 'byte',        '8'),
    ('PKS', 'shortint',    '8'),
    ('PKL', 'longint',     '8'),
    ('PKG', 'integer',     '8'),
    ('PKV', 'bit [3:0]',   "4'h7"),
    ('PKW', 'logic [7:0]', '8'),
    ('PKD', 'int',         "8'd8"),
    ('PKX', 'int',         '4+4'),
]


def decl(kw, ty, name, init):
    return f"  {kw} {ty + ' ' if ty else ''}{name} = {init};"


def main():
    L = []
    A = L.append
    A('// r10earl82 g5 — THE RANGE-BOUND DISCRIMINATOR GRID.  GENERATED by')
    A('// gen82.py; MEASUREMENT ONLY.  One consumer family, three positions.')
    A('package pk5_82;')
    for n, t, i in PKGS:
        A(decl('localparam', t, n, i))
    A('endpackage')
    A('')
    A('typedef struct packed { logic [3:0] a; } mr2_82;')
    A('')
    A('module enc82 import pk5_82::*; #(')
    A(',\n'.join(f"  parameter {t + ' ' if t else ''}{n} = {d}"
                 for n, t, d, _ in PARAMS))
    A(') (input logic clk, output logic o' + ',')
    A(',\n'.join(f"   input [{n}:0] p_{n}"
                 for n, _, _, _ in PARAMS) + ');')
    A('  typedef struct packed { logic [3:0] a; } mr_t;')
    for n, t, i in LOCALS:
        A(decl('localparam', t, n, i))
    names = [p[0] for p in PARAMS] + [l[0] for l in LOCALS] + [p[0] for p in PKGS]
    for n in names:
        A(f"  logic [{n}:0] n_{n};")          # packed range on a NET
        A(f"  mr_t  [{n}:0] v_{n};")          # packed range on a STRUCT-ARRAY VAR
        A(f"  logic [3:0]  u_{n} [{n}:0];")   # UNPACKED range-form dimension
    A('  logic acc;')
    A('  always_comb begin')
    A('    acc = clk;')
    for n in names:
        A(f"    acc = acc ^ n_{n}[0] ^ v_{n}[0].a[0] ^ u_{n}[0][0];")
    for n, _, _, _ in PARAMS:
        A(f"    acc = acc ^ p_{n}[0];")
    A('  end')
    A('  assign o = acc;')
    A('endmodule')
    A('')
    A('module top5_82 (input logic clk, output logic oa, ob);')
    A('  localparam int SRC      = 8;')
    A('  localparam int EXPR_LP  = 4 + 4;   // EXPRESSION-initialised')
    A('  localparam int ARITH_LP = 9 - 1;   // the `X-1` (paramIntEnc) form')
    ov = ',\n'.join(f"          .{n}({a})" for n, _, _, a in PARAMS if a)
    pc = ', '.join(f".p_{n}('0)" for n, _, _, _ in PARAMS)
    A(f"  enc82 #(\n{ov}) ia (.clk(clk), .o(oa), {pc});")
    A(f"  enc82 #(\n{ov}) ib (.clk(clk), .o(ob), {pc});")
    A('  // THE HOP CHAIN: a bare-decimal override at the TOP, passed down by')
    A('  // bare-reference actuals.  Every hop copies the Value verbatim, so the')
    A('  // width the leaf bound folds at must stay the unsized 64 of the')
    A("  // literal 40 -- Earlgrey's ibex MHPMCounterWidth shape.")
    A('  hop_mid82 #(.HW(40)) i_hop (.clk(clk));')
    A('endmodule')
    A('')
    A('module hop_mid82 #(parameter int unsigned HW = 8) (input logic clk);')
    A('  hop_leaf82 #(.HW(HW)) i_leaf (.clk(clk));')
    A('endmodule')
    A('')
    A('module hop_leaf82 #(parameter int unsigned HW = 8) (input logic clk);')
    A('  logic [HW:0] n_HOP;')
    A('  mr2_82 [HW:0] v_HOP;')
    A('  logic [3:0]  u_HOP [HW:0];')
    A('  logic acc2;')
    A('  always_comb acc2 = clk ^ n_HOP[0] ^ v_HOP[0].a[0] ^ u_HOP[0][0];')
    A('endmodule')
    sys.stdout.write('\n'.join(L) + '\n')


main()
