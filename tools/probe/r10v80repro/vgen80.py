#!/usr/bin/env python3
"""r10v80 — ADVERSARIAL grid generator for the verification of
   § ovHopOverriddenKeepsValue80.  MEASUREMENT ONLY.

Four arms, each self-contained (disjoint module names):
  v1_width80.sv  literal-spelling x declared-type x home, THREE hops
  v2_mid80.sv    the INTERMEDIATE declared types varied along the chain
  v3_home80.sv   gen-for / gen-if / nested gen / interface / program homes
  v4_shape80.sv  package params, localparam hops, multi-instance, override
                 written as an EXPRESSION / plain decimal / based literal
"""
import sys, os

# --- shared axes -----------------------------------------------------------
SRC1 = ["4'h2", "8'h2", "4'd2", "4'b10", "4'o7", "'h2", "'0", "'1",
        "4'sh2", "64'hFFFF", "2", "32'hDEADBEEF", "3'b101"]
MID1 = [("bit [3:0]", "b4"), ("logic [7:0]", "l8"), ("bit", "b1"),
        ("int", "ii"), ("int unsigned", "iu"), ("", "un"),
        ("byte", "by"), ("logic signed [3:0]", "ls4")]

def chain3(out, n, m1, m2, m3):
    out.append("module %s_lf #(parameter int unsigned E = 4)();" % n)
    out.append("  wire [31:0] w = E; endmodule")
    out.append("module %s_h3 #(parameter %s D = 3)();" % (n, m3 if m3 else "int unsigned"))
    out.append("  %s_lf #(.E(D)) u(); endmodule" % n)
    out.append("module %s_h2 #(parameter %s C = 2)();" % (n, m2 if m2 else "int unsigned"))
    out.append("  %s_h3 #(.D(C)) u(); endmodule" % n)
    d1 = ("parameter %s B = 1" % m1) if m1 else "parameter B = 1"
    out.append("module %s_h1 #(%s)();" % (n, d1))
    out.append("  %s_h2 #(.C(B)) u(); endmodule" % n)

def v1(path):
    out = ["// r10v80 v1_width80.sv GENERATED by vgen80.py. MEASUREMENT ONLY."]
    tops, lps = [], []
    k = 0
    for si, s in enumerate(SRC1):
        for m, mtag in MID1:
            for home in ("decl", "ovr", "lp"):
                k += 1
                n = "v1_%s_%s_%d" % (mtag, home, si)
                # hop0 default is the literal only in the DECL home
                out.append("module %s_lf #(parameter int unsigned E = 4)();" % n)
                out.append("  wire [31:0] w = E; endmodule")
                out.append("module %s_h3 #(parameter int unsigned D = 3)();" % n)
                out.append("  %s_lf #(.E(D)) u(); endmodule" % n)
                out.append("module %s_h2 #(parameter int unsigned C = 2)();" % n)
                out.append("  %s_h3 #(.D(C)) u(); endmodule" % n)
                d1 = ("parameter %s B = %s" % (m, s)) if m else ("parameter B = %s" % s)
                out.append("module %s_h1 #(%s)();" % (n, d1))
                out.append("  %s_h2 #(.C(B)) u(); endmodule" % n)
                if home == "decl":
                    tops.append("  %s_h1 u_%d();" % (n, k))
                elif home == "ovr":
                    tops.append("  %s_h1 #(.B(%s)) u_%d();" % (n, s, k))
                else:
                    lp = "lp_%d" % k
                    lps.append("  localparam %s %s = %s;" % (m, lp, s))
                    tops.append("  %s_h1 #(.B(%s)) u_%d();" % (n, lp, k))
    out.append("module topv1();")
    out.extend(lps); out.extend(tops); out.append("endmodule")
    open(path, "w").write("\n".join(out) + "\n")
    return k

MIDCOMBO = [
    ("bit [3:0]",    "bit [7:0]",    "int unsigned"),
    ("logic [7:0]",  "bit [3:0]",    "bit [3:0]"),
    ("int",          "bit",          "logic [7:0]"),
    ("int unsigned", "int unsigned", "bit [3:0]"),
    ("bit [7:0]",    "logic signed [7:0]", "int"),
    ("",             "",             ""),
    ("bit",          "int",          "int unsigned"),
    ("logic [31:0]", "bit [3:0]",    "byte"),
    ("byte",         "int",          "bit [7:0]"),
    ("logic signed [3:0]", "int", "int unsigned"),
    ("bit [63:0]",   "bit [3:0]",    "int"),
    ("int unsigned", "bit [3:0]",    "bit [7:0]"),
]
SRC2 = ["4'h2", "8'hff", "300", "'1", "16'habcd", "8'sh80"]

def v2(path):
    out = ["// r10v80 v2_mid80.sv GENERATED by vgen80.py. MEASUREMENT ONLY."]
