SRC3 = ["4'h2", "8'hff", "'1", "4'sh2", "300", "64'hFFFF"]

def v3(path):
    """homes: module scope, gen-for, gen-if(true/false), NESTED gen, interface,
       program.  One chain shape (bit[3:0] -> int unsigned -> int unsigned)."""
    out = ["// r10v80 v3_home80.sv GENERATED by vgen80.py. MEASUREMENT ONLY."]
    body = []
    k = 0
    for si, s in enumerate(SRC3):
        n = "v3_%d" % si
        chain3(out, n, "bit [3:0]", "int unsigned", "int unsigned")
        # interface + program flavours of the SAME chain
        out.append("interface %s_if #(parameter bit [3:0] B = 4'h1)();" % n)
        out.append("  localparam int unsigned C = B;")
        out.append("  wire [31:0] w = C; endinterface")
        out.append("program %s_pg #(parameter bit [3:0] B = 4'h1)();" % n)
        out.append("  localparam int unsigned C = B;")
        out.append("  initial begin if (C == 0) ; end endprogram")
        k += 1
        body.append("  %s_h1 #(.B(%s)) u_m%d();" % (n, s, si))
        body.append("  for (genvar gi = 0; gi < 2; gi++) begin : g_for%d" % si)
        body.append("    %s_h1 #(.B(%s)) u_gf%d();" % (n, s, si))
        body.append("  end")
        body.append("  if (1) begin : g_if%d" % si)
        body.append("    %s_h1 #(.B(%s)) u_gi%d();" % (n, s, si))
        body.append("    if (1) begin : g_nest%d" % si)
        body.append("      %s_h1 #(.B(%s)) u_gn%d();" % (n, s, si))
        body.append("    end")
        body.append("  end else begin : g_else%d" % si)
        body.append("    %s_h1 #(.B(%s)) u_ge%d();" % (n, s, si))
        body.append("  end")
        body.append("  %s_if #(.B(%s)) u_if%d();" % (n, s, si))
        body.append("  %s_pg #(.B(%s)) u_pg%d();" % (n, s, si))
    out.append("module topv3();")
    out.extend(body)
    out.append("endmodule")
    open(path, "w").write("\n".join(out) + "\n")
    return k

def v4(path):
    """package parameters, localparam hops, MULTI-instance with two different
       overrides, override written as an EXPRESSION / plain decimal / based
       literal, and a 3-instance module."""
    o = ["// r10v80 v4_shape80.sv GENERATED by vgen80.py. MEASUREMENT ONLY.",
         "package v4_pkg;",
         "  parameter bit [3:0] PB4 = 4'h2;",
         "  parameter int unsigned PIU = 8'hff;",
         "  parameter PUN = 16'habcd;",
         "  localparam logic [7:0] PL8 = 8'h5a;",
         "endpackage"]
    for i, (m1, m2) in enumerate([("bit [3:0]", "int unsigned"),
                                  ("logic [7:0]", "bit [3:0]"),
                                  ("int", "bit [7:0]"),
                                  ("", "int unsigned")]):
        n = "v4_c%d" % i
        chain3(o, n, m1, m2, "int unsigned")
    o.append("module topv4();")
    o.append("  import v4_pkg::*;")
    # package-parameter actuals
    o.append("  v4_c0_h1 #(.B(v4_pkg::PB4)) u_pk0();")
    o.append("  v4_c1_h1 #(.B(v4_pkg::PIU)) u_pk1();")
    o.append("  v4_c2_h1 #(.B(v4_pkg::PUN)) u_pk2();")
    o.append("  v4_c3_h1 #(.B(v4_pkg::PL8)) u_pk3();")
    o.append("  v4_c0_h1 #(.B(PB4)) u_pkb0();")
    # localparam hops of many types
    o.append("  localparam bit [3:0]  L_B4  = 4'h2;")
    o.append("  localparam logic [7:0] L_L8 = 8'hff;")
    o.append("  localparam int        L_II  = 4'sh2;")
    o.append("  localparam            L_UN  = 4'o7;")
    o.append("  localparam bit [63:0] L_W   = 64'hFFFF;")
    for j, lp in enumerate(["L_B4", "L_L8", "L_II", "L_UN", "L_W"]):
        o.append("  v4_c%d_h1 #(.B(%s)) u_lp%d();" % (j % 4, lp, j))
    # override written as an EXPRESSION / decimal / based literal — controls
    o.append("  v4_c0_h1 #(.B(4'h1 + 4'h1)) u_ex0();")
    o.append("  v4_c0_h1 #(.B(2)) u_dc0();")
    o.append("  v4_c0_h1 #(.B(4'h2)) u_bl0();")
    o.append("  v4_c1_h1 #(.B(L_B4 + 1)) u_ex1();")
    o.append("  v4_c1_h1 #(.B({4'h0, 4'h2})) u_ex2();")
    o.append("  v4_c2_h1 #(.B(8'hff >> 2)) u_ex3();")
    o.append("  v4_c3_h1 #(.B(1 ? 8'h5a : 8'h00)) u_ex4();")
    # multi-instance: same module, 1..3 instances, two DIFFERENT overrides
    o.append("  v4_c0_h1 #(.B(4'h3)) u_mi0();")
    o.append("  v4_c0_h1 #(.B(4'h4)) u_mi1();")
    o.append("  v4_c0_h1 #(.B(8'h5)) u_mi2();")
    o.append("  v4_c1_h1 u_nd0();")            # not overridden at all
    o.append("  v4_c1_h1 #(.B(16'habcd)) u_nd1();")
    o.append("endmodule")
    open(path, "w").write("\n".join(o) + "\n")
    return 1

d = sys.argv[1]
print("v1", v1(os.path.join(d, "v1_width80.sv")))
print("v2", v2(os.path.join(d, "v2_mid80.sv")))
print("v3", v3(os.path.join(d, "v3_home80.sv")))
print("v4", v4(os.path.join(d, "v4_shape80.sv")))
