#!/usr/bin/env python3
# r10earl64 — GRID A2 generator: the CONSUMER half of § elabCaPortParamPaCopy64.
# One sub-module per DECLARED TYPE, instantiated once per OVERRIDE SPELLING,
# each reading the parameter from a TERNARY ARM of an ELAB gen-scope
# cont_assign (the position the law owns).  MEASUREMENT ONLY.
import sys
TYPES = [("int","i"),("int unsigned","iu"),("integer","ig"),("byte","by"),
         ("shortint","si"),("longint","li"),("bit","b1"),("bit [7:0]","b8"),
         ("logic [31:0]","l32"),("logic signed [31:0]","ls32"),
         ("logic [3:0]","l4"),("","un")]
OVS = [("4'b1010","bin"),("8'hab","hex"),("4'd5","sd"),("300","dec"),
       ("EXPR","expr"),("8'o17","oct"),("-3","neg"),("NONE","dflt")]
out=[]
out.append("// r10earl64 GRID A2 — generated by genA2_64.py.  MEASUREMENT ONLY.")
out.append("module topA2(input logic c, output logic [63:0] o);")
out.append("  localparam int EXPRP = 2 * 3;")
lines=[]; insts=[]; n=0
for ty,tk in TYPES:
    decl = ("parameter %s P = 1" % ty) if ty else "parameter P = 1"
    lines.append("module sub_%s #(%s) (input logic c, output logic [63:0] q);" % (tk, decl))
    lines.append("  if (1) begin : g_if")
    lines.append("    assign q = c ? 64'(P) : 64'(P);")
    lines.append("  end")
    lines.append("endmodule")
    for ov,ok in OVS:
        n += 1
        a = "" if ov=="NONE" else ("#(.P(EXPRP)) " if ov=="EXPR" else "#(.P(%s)) " % ov)
        insts.append("  sub_%s %si_%s_%s (c, w%d);" % (tk, a, tk, ok, n))
for i in range(1,n+1):
    out.append("  wire [63:0] w%d;" % i)
out += insts
out.append("  assign o = " + " ^ ".join("w%d"%i for i in range(1,n+1)) + ";")
out.append("endmodule")
print("\n".join(lines))
print("\n".join(out))
